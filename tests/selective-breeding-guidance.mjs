import assert from 'node:assert/strict';
import {Simulation} from '../src/sim/simulation.js';
import {SPECIES} from '../src/organisms/species.js';
import {founderPlan,recombineBodyPlans} from '../src/lineage/body-inheritance.js';
import {makePlan,serializePlan} from '../src/lineage/body-plan.js';
import {comparePhysicalBuilds,offspringPartOrigins,originSummary} from '../src/lineage/breeding-guidance.js';
import {buildJournalEntry} from '../src/ui/journal.js';
import {createSimulationSnapshot,restoreSimulationSnapshot} from '../src/persistence/save-manager.js';

const base=founderPlan();
const placements=plan=>plan.nodes.map(n=>({partId:n.partId,parent:n.parent,socket:n.socket}));
const change=(which,addition)=>makePlan([...placements(base).map(n=>n.socket===which?{...n,partId:'spring-leg'}:n),...addition]);
const motherPlan=change('limb.3',[{partId:'signal-crest',parent:'root',socket:'dorsal'}]);
const fatherPlan=change('limb.7',[{partId:'flag-tail',parent:'root',socket:'tail'}]);
const untouched=JSON.stringify([serializePlan(motherPlan),serializePlan(fatherPlan)]);
const same=comparePhysicalBuilds(motherPlan,serializePlan(motherPlan));
assert.equal(same.exact,true);
const different=comparePhysicalBuilds(motherPlan,fatherPlan);
assert.equal(different.exact,false);
assert.ok(different.differences.some(v=>v.location==='limb 3'));
assert.ok(different.differences.some(v=>v.location==='limb 7'));
const fakeChild=makePlan([...placements(motherPlan).filter(n=>n.socket!=='dorsal'),{partId:'flag-tail',parent:'root',socket:'tail'}]);
const origins=offspringPartOrigins(serializePlan(fakeChild),serializePlan(motherPlan),serializePlan(fatherPlan));
assert.ok(origins.both.length>=1,'same sockets are marked shared');
assert.equal(origins.mother.find(x=>x.location==='limb 3')?.part,'spring leg');
assert.equal(origins.father.find(x=>x.location==='tail')?.part,'flag tail');
assert.ok(originSummary(origins).includes('From father'));
assert.equal(JSON.stringify([serializePlan(motherPlan),serializePlan(fatherPlan)]),untouched,'guidance must not edit plans');

const sim=new Simulation('GENVO8-GUIDED-BREEDING',{player:true});
const player=sim.player();
const mate=sim.animals.find(a=>a.alive&&a.species==='genvo'&&a.sex!==player.sex&&a.id!==player.id);
assert.ok(mate,'existing world has viable genvo opposite-sex candidate');
player.bodyPlan=motherPlan;mate.bodyPlan=fatherPlan;
const mother=player.sex==='F'?player:mate,father=player.sex==='M'?player:mate;
const gestationalMother=mother.bodyPlan,gestationalFather=father.bodyPlan;
for(const a of [player,mate])a.age=SPECIES.genvo.maturity+3;
const beforeRng=sim.rng.state;
comparePhysicalBuilds(player,mate);offspringPartOrigins(fakeChild,player,mate);
assert.equal(sim.rng.state,beforeRng,'read-only reports never draw RNG');
sim.bodyVariationChance=0;
mother.pregnant={fatherId:father.id,days:0,totalDays:16,startedDay:sim.day,startedYear:sim.year,plannedLitterSize:2};
mother.energy=SPECIES.genvo.maxEnergy;mother.hydration=SPECIES.genvo.maxHydration;
const born=sim.giveBirth(mother);
assert.ok(born.length>=1,'normal simulation registers actual offspring');
const child=born[0],rec=sim.lineage.records.get(child.id);
assert.ok(rec.parentBodyPlans?.length===2);
assert.equal(comparePhysicalBuilds(rec.parentBodyPlans[0],gestationalMother).exact,true);
assert.equal(comparePhysicalBuilds(rec.parentBodyPlans[1],gestationalFather).exact,true);
const entry=buildJournalEntry(sim,child.id);
assert.ok(entry?.inheritance?.includes('Shared'));
assert.ok(entry.parentBuilds.includes('Parents differ'));
// A parent changing or dying later must not rewrite an offspring's birth-history evidence.
mother.bodyPlan=base;father.bodyPlan=base;
assert.equal(buildJournalEntry(sim,child.id).inheritance,entry.inheritance);
const snapshot=structuredClone(createSimulationSnapshot(sim));
const loaded=restoreSimulationSnapshot(snapshot);
assert.deepEqual(loaded.lineage.records.get(child.id).parentBodyPlans,rec.parentBodyPlans);
assert.equal(buildJournalEntry(loaded,child.id).inheritance,entry.inheritance);
// Historic saves missing this new, optional evidence should display an honest unknown.
delete loaded.lineage.records.get(child.id).parentBodyPlans;
assert.match(buildJournalEntry(loaded,child.id).inheritance,/not recorded/);
console.log('selective breeding: exact socket comparison, real parent-origin history, journal and save continuity ok');
