import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {Simulation} from '../src/sim/simulation.js';
import {SPECIES} from '../src/organisms/species.js';
import {planetaryWalkIntent,planetaryPosition,planetaryPositionLabel,WALK_FRONTIER_MARGIN} from '../src/world/planetary-walkthrough.js';
import {planetaryTravelAvailability,crossPlanetaryBorder} from '../src/world/planetary-travel.js';
import {createSimulationSnapshot,restoreSimulationSnapshot} from '../src/persistence/save-manager.js';

const markup=readFileSync(new URL('../index.html',import.meta.url),'utf8');
const main=readFileSync(new URL('../src/main.js',import.meta.url),'utf8');
assert.match(markup,/value="planetary\/1" selected>Procedural planet/,'new worlds explicitly select procedural planetary geography');
assert.match(markup,/value="freshwater\/1">Legacy local world/,'legacy 128x128 new-world option remains');
assert.match(main,/planetaryWalkIntent\(sim,/,'frame integrates actual outward walking');
assert.match(main,/travelPlanetaryRegion\(\{automatic:true\}\)/,'walking invokes canonical regional transfer');
assert.match(main,/keepMovement:automatic/,'held input persists across world swaps');
assert.match(markup,/id="planetLocation"/,'the planet exposes global position rather than only 128x128 local coordinates');
assert.equal(planetaryWalkIntent(null,{right:true}),null);
const local=new Simulation('OLD-SMALL-MAP',{player:true});
assert.equal(planetaryWalkIntent(local,{right:true}),null,'historical freshwater worlds are never silently converted');

const sim=new Simulation('PLANET-B0-A',{player:true,worldGenerator:'planetary/1'}),animal=sim.player();
assert.deepEqual(planetaryPosition(sim),{regionX:0,regionY:0,worldX:animal.x,worldY:animal.y});
assert.match(planetaryPositionLabel(sim),/Planet \d+, \d+ · Region 0, 0/);
assert.equal(planetaryWalkIntent(sim,{right:true}),null,'no crossing while still walking inside the region');
animal.energy=SPECIES[animal.species].maxEnergy*.95;
animal.hydration=SPECIES[animal.species].maxHydration*.95;
let front=null;
for(let y=8.5;y<119;y++){
 animal.x=125.2;animal.y=y;
 const result=planetaryTravelAvailability(sim);
 if(result.enabled){front=result;break}
}
assert.ok(front&&front.direction==='east','find actually traversable planetary land border');
assert.ok(front.distance<=WALK_FRONTIER_MARGIN);
const originPos=planetaryPosition(sim),sourceRng=sim.rng.state,sourceStock=sim.world.plants.bramble[sim.world.idx(21,41)];
assert.equal(planetaryWalkIntent(sim,{right:true}),'east');
assert.equal(planetaryWalkIntent(sim,{up:true}),null,'sideways movement along the border cannot trigger crossing');
assert.equal(planetaryWalkIntent(sim,{left:true}),null,'walking inland cannot trigger crossing');
assert.equal(planetaryWalkIntent(sim,{}),null,'idle at the frontier never leaves a region');
sim.paused=true;assert.equal(planetaryWalkIntent(sim,{right:true}),null,'no automatic travel while paused');sim.paused=false;
sim.playerAutonomy=true;assert.equal(planetaryWalkIntent(sim,{right:true}),null,'no automatic travel while AI controls the creature');sim.playerAutonomy=false;
animal.x=120;assert.equal(planetaryWalkIntent(sim,{right:true}),null,'not a premature transition five tiles from the edge');
animal.x=125.2;assert.equal(sim.rng.state,sourceRng,'read-only frontier intention does not alter ecology');
const first=crossPlanetaryBorder(sim);assert.ok(first.ok,first.message);
const next=first.simulation,traveler=next.player();
assert.deepEqual(next.world.regionOrigin,{x:128,y:0},'walk east advances to the next adjacent region of the same planet');
assert.equal(traveler.id,animal.id);
assert.deepEqual(traveler.bodyPlan,animal.bodyPlan);
assert.deepEqual(traveler.genes,animal.genes);
assert.equal(next.animals.filter(a=>a.id===traveler.id).length,1);
assert.notDeepEqual(next.world.moisture,sim.world.moisture,'new region samples a different stretch of global planetary geography');
const global=planetaryPosition(next);
assert.equal(global.regionX,128);assert.equal(global.regionY,0);
assert.equal(global.worldX,128+traveler.x);
assert.ok(global.worldX>originPos.worldX,'absolute position advances through the original 128-tile boundary');
assert.equal(planetaryWalkIntent(next,{right:true}),null,'holding the outward key after entering is not reversed by the arrival border');
assert.equal(next.planetaryTravel.sessions.length,1);
assert.equal(next.planetaryTravel.sessions[0].key,'0,0');
const restored=restoreSimulationSnapshot(structuredClone(createSimulationSnapshot(next,{savedAt:'fixed',reason:'walkthrough'})));
assert.deepEqual(planetaryPosition(restored),global,'global position is reconstructed from durable regional origin');
restored.player().x=2.5;restored.player().y=front.point.y;
assert.equal(planetaryWalkIntent(restored,{left:true}),'west','walking back west requests the real home region');
const beforeHome=planetaryTravelAvailability(restored);assert.ok(beforeHome.enabled,beforeHome.reason);
const back=crossPlanetaryBorder(restored);assert.ok(back.ok,back.message);
assert.deepEqual(back.simulation.world.regionOrigin,{x:0,y:0});
assert.equal(back.simulation.world.plants.bramble[sim.world.idx(21,41)],sourceStock,'return visits must not regenerate consumed or modified stocks');
assert.equal(back.simulation.playerId,animal.id,'same individual walks home without duplicate genealogy');
assert.ok(back.simulation.planetaryTravel.sessions.some(s=>s.key==='128,0'));
console.log('Procedural planet New World default, held-direction frontier, real adjacent ecology, identity and save/return: PASS');
