import assert from 'node:assert/strict';
import {Simulation} from '../src/sim/simulation.js';
import {CAVES,initializeCaves,erodeNaturalCaves,naturalErosionEligible,validateCaves} from '../src/world/natural-caves.js';
import {solidTerrainTotal,refreshPassages} from '../src/world/subsurface.js';
import {excavatePassage} from '../src/world/subsurface.js';
import {FounderDesign} from '../src/lineage/founder-design.js';
import {burrowingAnatomy,moveUnderground} from '../src/lineage/burrowing.js';
import {stepCaveTransit} from '../src/lineage/cave-traversal.js';
import {createSimulationSnapshot,restoreSimulationSnapshot} from '../src/persistence/save-manager.js';
import {routePlanetaryRunoff,totalPlanetarySurfaceWater} from '../src/world/planetary-runoff.js';
import {deriveDrainage} from '../src/world/topography.js';
import {emptySubsurface} from '../src/world/subsurface.js';
import {caveFracture} from '../src/world/natural-caves.js';
import {TERRAIN_SEDIMENT} from '../src/world/terrain-sediment.js';
const sim=new Simulation('CAVES-GEOLOGY',{naturalCaves:false}),w=sim.world;
const before=solidTerrainTotal(w),rng=sim.rng.state,water=w.water.slice();
initializeCaves(w,{generate:true});
assert.ok(w.subsurface.initialCaves>0,'seed exposes real generated entrances');
assert.ok(w.subsurface.passages.size>w.subsurface.initialCaves,'entrances connect to interior cells');
assert.ok(Math.abs(solidTerrainTotal(w)-before)<1e-7,'initial cavities fund actual surface material');
assert.equal(sim.rng.state,rng,'geology does not consume biological RNG');assert.deepEqual(w.water,water);
validateCaves(w,CAVES.policy);
const repeat=new Simulation('CAVES-GEOLOGY',{naturalCaves:false});initializeCaves(repeat.world,{generate:true});
assert.deepEqual(repeat.world.subsurface,w.subsurface,'stateless initial geology is deterministic');
let edge;
for(let i=0;i<w.len;i++){const j=w.terrain.downstream[i];if(j>=0&&!w.subsurface.passages.has(i)&&naturalErosionEligible(w,i,j)){edge=[i,j];break}}
assert.ok(edge,'generated drainage has eligible dry substrate');
const [i,j]=edge,unchanged=structuredClone(w.subsurface);
assert.equal(erodeNaturalCaves(w,[[i,j,0]]),0);assert.deepEqual(w.subsurface,unchanged);
assert.throws(()=>erodeNaturalCaves(w,[[i,j,1],[i,j,NaN]]),/flux/);assert.deepEqual(w.subsurface,unchanged,'validate the full flux batch before mutation');
const total=solidTerrainTotal(w),moved=erodeNaturalCaves(w,[[i,j,1]]);
assert.ok(moved>0&&moved<.001501,'real flow funds bounded undercutting');
assert.ok(w.subsurface.caveErosion.has(i),'partial erosion does not create an occupiable passage');
assert.ok(Math.abs(solidTerrainTotal(w)-total)<1e-7);validateCaves(w,CAVES.policy);
const partial=w.subsurface.caveErosion.get(i);w.terrain.elevation[i]=(partial.floor+1)/20;
const beforeCollapse=solidTerrainTotal(w);refreshPassages(w);
assert.equal(w.subsurface.caveErosion.has(i),false,'thin partial roofs collapse');
assert.ok(Math.abs(solidTerrainTotal(w)-beforeCollapse)<1e-6);validateCaves(w,CAVES.policy);
// Digging reuses a partial void rather than crediting a second cavity.
const filled=repeat.world;const edge2=filled.terrain.downstream[i];assert.ok(erodeNaturalCaves(filled,[[i,edge2,1]])>0);
const beforeDig=solidTerrainTotal(filled);assert.ok(excavatePassage(filled,i));assert.equal(filled.subsurface.caveErosion.has(i),false);validateCaves(filled,CAVES.policy);assert.ok(Math.abs(solidTerrainTotal(filled)-beforeDig)<1e-7);
sim.caveRules=CAVES.policy;const a=sim.player(),entry=[...w.subsurface.passages.values()].find(p=>p.entry&&!p.closed);
a.bodyPlan=new FounderDesign('sandbox').draft.plan;a.x=entry.i%w.n+.5;a.y=(entry.i/w.n|0)+.5;
assert.equal(burrowingAnatomy(a),false);const geometry=structuredClone(w.subsurface),energy=a.energy;
assert.ok(sim.playerInteract(null,'cave').ok,'ordinary Interact enters without digging anatomy');
stepCaveTransit(sim,a,.2);assert.equal(a.underground,undefined,'entry takes real time');
assert.equal(sim.resourceAvailability('eat').enabled,false);assert.equal(sim.playerCombat.attackAvailability().enabled,false);
const snapshot=structuredClone(createSimulationSnapshot(sim));const restored=restoreSimulationSnapshot(structuredClone(snapshot));
assert.deepEqual(restored.player().caveTransit,a.caveTransit,'exact mid-entrance continuation');
const invalid=structuredClone(snapshot);invalid.animals.find(v=>v.id===a.id).caveTransit.i++;
assert.throws(()=>restoreSimulationSnapshot(invalid),/cave transition/);
for(let k=0;k<5;k++)stepCaveTransit(sim,a,.2);assert.ok(a.underground);assert.ok(a.energy<energy);
assert.deepEqual(w.subsurface,geometry,'using an existing cave excavates no new material');
assert.ok(sim.playerInteract(null,'cave').ok);assert.equal(moveUnderground(sim,a,1,0,.1),false,'exit movement remains anchored');
for(let k=0;k<6;k++)stepCaveTransit(sim,a,.2);assert.equal(a.underground,undefined);
// The ordinary rainfall/runoff authority funds undercutting once per flow.
const land={n:4,len:16,seedHash:0,water:new Uint8Array(16),isPlayable:()=>true,buildHydrology(){},subsurface:emptySubsurface(),terrain:{schema:1,elevation:new Float32Array(16).fill(.95)}};
land.terrain.elevation[5]=.85;land.terrain.elevation[6]=.2;deriveDrainage(land);initializeCaves(land);
while(caveFracture(land,5)<=.65)land.seedHash++;
const row={day:1,waterBefore:.18,waterInput:0,waterOutput:0};land.environment={schema:5,overland:new Float64Array(16),volume:new Float64Array(16),totals:{},lastDay:row,terrainSedimentPolicy:TERRAIN_SEDIMENT.policy};land.environment.overland[5]=.18;
const terrainBefore=solidTerrainTotal(land),sourceHeight=land.terrain.elevation[5];
routePlanetaryRunoff(land,new Float64Array(16),1);
assert.ok(land.environment.lastDay.naturalCaveErosion>0);assert.equal(land.terrain.elevation[5],sourceHeight,'flow work is not also charged to surface erosion');
assert.ok(Math.abs(totalPlanetarySurfaceWater(land)-.18)<1e-12);assert.ok(Math.abs(solidTerrainTotal(land)-terrainBefore)<1e-7);validateCaves(land,CAVES.policy);
for(let day=0;day<60&&!land.subsurface.passages.get(5)?.entry;day++)erodeNaturalCaves(land,[[5,6,1]]);
assert.ok(land.subsurface.passages.get(5)?.entry,'continued funded undercutting exposes an actual entrance');
assert.ok(Math.abs(solidTerrainTotal(land)-terrainBefore)<1e-7);validateCaves(land,CAVES.policy);
assert.throws(()=>validateCaves(land,undefined),/recorded policy/);
console.log('Natural caves PASS: seeded connected geology, material/water/RNG conservation, bounded erosion and collapse, partial-void digging, ordinary non-digger entry/exit, transition restrictions and exact mid-entry saves.');
