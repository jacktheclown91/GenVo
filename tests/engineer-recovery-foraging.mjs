import {provideRootFood} from './helpers/finite-root-food.js';
import assert from 'node:assert/strict';
import {Simulation} from '../src/sim/simulation.js';
import {SPECIES} from '../src/organisms/species.js';
import {needsRecoveryForage,ENGINEER_RECOVERY} from '../src/lineage/engineer-recovery-foraging.js';
import {createSimulationSnapshot,restoreSimulationSnapshot} from '../src/persistence/save-manager.js';
const sim=new Simulation('ER-RECOVERY-CONTRACT',{player:false});
const a=sim.animals.find(a=>a.alive&&a.species==='rootling');
assert.ok(a?.bodyPlan);const s=SPECIES[a.species];
const i=sim.world.idx(a.x,a.y);const oldWater=sim.world.water[i];
sim.world.water[i]=0;sim.world.fertility[i]=.72;provideRootFood(sim,a);
a.health=ENGINEER_RECOVERY.maxHealth-2;a.energy=s.maxEnergy*.73;a.hydration=s.maxHydration*.74;
assert.equal(needsRecoveryForage(a),true);
const far={x:a.x+5,y:a.y+2,kind:'sunmoss'};
assert.equal(sim.partAbilities.digDecision(a,{food:far})?.kind,'roots','injured engineer uses actual roots before exhausting its energy reserve');
assert.equal(sim.partAbilities.digDecision(a,{food:{...far,x:a.x+.6,y:a.y}}),null,'nearby plants still take precedence');
sim.world.fertility[i]=.22;assert.equal(sim.partAbilities.digDecision(a,{food:far}),null,'poor ground remains unsuitable');sim.world.fertility[i]=.72;
a.health=92;assert.equal(needsRecoveryForage(a),false);assert.equal(sim.partAbilities.digDecision(a,{food:far}),null,'healthy animals retain the old hunger threshold');
a.health=63;a.energy=s.maxEnergy*.80;assert.equal(needsRecoveryForage(a),false,'adequate food reserve does not trigger recovery foraging');
a.energy=s.maxEnergy*.73;
const withoutAnatomy={...a,bodyPlan:null};assert.equal(needsRecoveryForage(withoutAnatomy),false);assert.equal(sim.partAbilities.digDecision(withoutAnatomy,{food:far}),null);
const originEnergy=a.energy,originWater=a.hydration,rng=sim.rng.state;
const action=sim.partAbilities.dig(a);assert.equal(action.ok,true,'live digging uses existing action and cooldown');
assert.ok(a.energy>originEnergy);assert.equal(a.hydration,originWater,'foodWater=false grants no new hydration');assert.ok(sim.world.plants.marshroot[i]<1,'recovery action debits fixture food');
assert.equal(sim.partAbilities.dig(a).ok,false,'existing per-action cooldown remains binding');
assert.equal(sim.rng.state,rng,'recovery-root decision consumes no random values');
assert.ok(sim.partAbilities.soilDisturbance.size>0);
const restored=restoreSimulationSnapshot(structuredClone(createSimulationSnapshot(sim)));
const copy=restored.animals.find(x=>x.id===a.id);
assert.equal(needsRecoveryForage(copy),needsRecoveryForage(a));
assert.equal(restored.partAbilities.soilDisturbance.size,sim.partAbilities.soilDisturbance.size);
assert.equal(restored.partAbilities.dug[i],sim.partAbilities.dug[i]);
sim.world.water[i]=oldWater;
console.log('ER injury-sensitive finite-root recovery, anatomy, no bonus, cooldown, RNG and persistence: PASS');
