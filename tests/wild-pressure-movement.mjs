import assert from 'node:assert/strict';
import {Simulation} from '../src/sim/simulation.js';
import {SPECIES} from '../src/organisms/species.js';
import {forageRangeEffect} from '../src/lineage/effects.js';
const sim=new Simulation('WILD-PRESSURE-MOVEMENT',{player:false}),w=sim.world;
const a=sim.animals.find(a=>a.species==='rootling'),competitors=sim.animals.filter(a=>a.species==='mosskip').slice(0,15);
w.water.fill(0);w.buildLandRegions();w.buildHydrology();
for(const field of Object.values(w.plants))field.fill(1);
sim.animals=[a,...competitors];a.x=50.5;a.y=50.5;a.age=100;a.energy=SPECIES.rootling.maxEnergy*.95;a.reproCooldown=0;
for(const b of competitors){b.x=a.x+.1;b.y=a.y+.1}
sim.rebuildSpatial();assert.equal(sim.carrying.breedingState(a).allowed,false,'fixture is blocked by real nearby competing consumers');
const position={x:a.x,y:a.y},rng=sim.rng.state,births=sim.stats.births;
const recommendation=sim.migration.recommend(a);
assert.ok(recommendation?.shouldMigrate,'wild adults can respond to perceived crowding without lineage-only migration authority');
assert.ok(sim.canReach(a,recommendation.target.x,recommendation.target.y));
assert.ok(Math.hypot(recommendation.target.x-a.x,recommendation.target.y-a.y)<=9*a.genes.senses*forageRangeEffect(sim,a));
assert.equal(a.x,position.x);assert.equal(a.y,position.y);assert.equal(sim.rng.state,rng);assert.equal(sim.stats.births,births,'recommendation creates no rescue births');
const prospect=sim.carrying.breedingState(a,{at:{x:90,y:90}});
assert.equal(prospect.local,1,'empty prospective habitat includes the migrant itself');
assert.equal(a.x,position.x);assert.equal(a.y,position.y);
assert.ok(sim.migration.begin(a,recommendation.target,'competing consumers'));
assert.equal(a.x,position.x);assert.equal(a.y,position.y,'committing never teleports');
sim.phaseDecision(null);assert.equal(a.intent,'migrate','routine grouping cannot suppress committed travel');
const beforeDistance=Math.hypot(a.x-recommendation.target.x,a.y-recommendation.target.y);
sim.phaseMovement();
const moved=Math.hypot(a.x-position.x,a.y-position.y);
assert.ok(moved>0&&moved<1,'normal movement makes a bounded physical step');
assert.ok(Math.hypot(a.x-recommendation.target.x,a.y-recommendation.target.y)<beforeDistance);
assert.ok(sim.canOccupy(a,a.x,a.y));
assert.equal(sim.stats.births,births);
assert.equal(sim.migration.begin(a,{x:110,y:110}),false,'unperceived habitat cannot become a committed route');
console.log('wild crowding response uses perceived connected habitat: PASS');
