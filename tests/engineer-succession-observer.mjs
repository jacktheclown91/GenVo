import assert from 'node:assert/strict';
import {Simulation} from '../src/sim/simulation.js';
import {CFG} from '../src/sim/config.js';
import {hasPart} from '../src/lineage/part-abilities.js';
import {createSimulationSnapshot,restoreSimulationSnapshot} from '../src/persistence/save-manager.js';
import {ENGINEER_SUCCESSION} from '../src/ecology/engineer-succession.js';
const sim=new Simulation('EL-RESIDENCY-UNIT',{player:false});
const worker=sim.animals.find(a=>a.alive&&hasPart(a,'digging-forelimb'));
assert.ok(worker);
sim.animals=[worker];
const at=(x,y,day)=>{worker.x=x+.5;worker.y=y+.5;sim.day=day;sim.tickCount=day*CFG.dayTicks;sim.regionalEcology.observe();};
const A=sim.regionalEcology.keyAt(33,33),B=sim.regionalEcology.keyAt(65,33);
const originalRng=sim.rng.state;
const plants=structuredClone(sim.world.plants),seeds=structuredClone(sim.world.seedBank);
for(let day=1;day<=2;day++)at(33,33,day);
for(let day=3;day<=8;day++)at(65,33,day);
let events=sim.regionalEcology.engineerTransitions(A);
assert.equal(events.length,1);
assert.equal(events[0].type,'vacancy');
assert.equal(events[0].firstEmptyDay,3);
assert.equal(sim.regionalEcology.engineerTransitions(B).length,0,'First-ever occupation cannot be a reoccupation');
for(let day=9;day<=11;day++)at(33,33,day);
events=sim.regionalEcology.engineerTransitions(A);
assert.equal(events[1].type,'reoccupation');
assert.equal(events[1].source,'observed-crossing');
assert.equal(events[1].fromRegion,B);
assert.equal(events[1].individualId,worker.id);
assert.equal(events[1].firstObservedDay,9);
assert.equal(events[1].day,11);
assert.equal(events[1].workSinceReturn,0);
// Provenance of return work is from real successful anatomy-gated action.
sim.world.water[sim.world.idx(worker.x,worker.y)]=0;
assert.equal(sim.partAbilities.dig(worker).ok,true);
assert.equal(sim.regionalEcology.engineerTransitions(A).at(-1).workSinceReturn,1);
assert.equal(sim.partAbilities.dig(worker).ok,false);
assert.equal(sim.regionalEcology.engineerTransitions(A).at(-1).workSinceReturn,1);
const snap=createSimulationSnapshot(sim),restored=restoreSimulationSnapshot(structuredClone(snap));
assert.deepEqual(restored.regionalEcology.engineerTransitions(A),sim.regionalEcology.engineerTransitions(A));
assert.deepEqual(restored.regionalEcology.records,sim.regionalEcology.records);
assert.equal(sim.rng.state,originalRng,'Passive occupancy and work receipt never consume RNG');
assert.deepEqual(sim.world.plants,plants,'Observer does not mutate plant stocks');
assert.deepEqual(sim.world.seedBank,seeds,'Observer does not mutate seed banks');
const copy=sim.regionalEcology.engineerTransitions(A);copy[0].type='tamper';
assert.equal(sim.regionalEcology.engineerTransitions(A)[0].type,'vacancy');
// A 1-day excursion is not a certified engineer loss, and a 2-day stopover is
// not a confirmed return. These cases are especially important at chunk edges.
for(let day=12;day<=13;day++)at(65,33,day);
for(let day=14;day<=15;day++)at(33,33,day);
assert.equal(sim.regionalEcology.engineerTransitions(A).length,2);
for(let day=16;day<=21;day++)at(65,33,day);
for(let day=22;day<=23;day++)at(33,33,day);
assert.equal(sim.regionalEcology.engineerTransitions(A).length,3,'Two-day visit must not confirm reoccupation');
const frozenWork=sim.regionalEcology.engineerTransitions(A)[1].workSinceReturn;
sim.regionalEcology.noteSoilDig(worker);
assert.equal(sim.regionalEcology.engineerTransitions(A)[1].workSinceReturn,frozenWork,'New work after a vacancy cannot be charged to an earlier return');
at(65,33,24);
assert.equal(sim.regionalEcology.engineerTransitions(A).length,3);
for(let day=25;day<=27;day++)at(33,33,day);
assert.equal(sim.regionalEcology.engineerTransitions(A).length,4);
assert.ok(sim.regionalEcology.engineerTransitions(A).length<=ENGINEER_SUCCESSION.eventLimit);
console.log('regional engineer vacancies, identified cross-region returns, sustained residence, real-work receipts, no false stopovers, persistence, RNG and finite stock neutrality: PASS');
