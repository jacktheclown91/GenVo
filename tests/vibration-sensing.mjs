import assert from 'node:assert/strict';
import {GROUND_VIBRATIONS,STRATUM_SENSES,vibrationPath} from '../src/ecology/stratum-senses.js';
import {sensoryProfile,groundVibrationCue} from '../src/ecology/sensory-world.js';
import {Simulation} from '../src/sim/simulation.js';
import {createSimulationSnapshot,restoreSimulationSnapshot} from '../src/persistence/save-manager.js';
const n=12,w={n,len:n*n,water:new Uint8Array(n*n),moisture:new Float32Array(n*n),
 idx:(x,y)=>Math.floor(y)*n+Math.floor(x),sameLand:()=>true};
const sim={world:w,tickCount:40,vibrationRules:GROUND_VIBRATIONS.policy,stratumSenseRules:STRATUM_SENSES.policy};
const listener={id:1,alive:true,species:'genvo',x:2.5,y:3.5,genes:{senses:1},bodyPlan:{nodes:[{partId:'sensory-quills'}]}};
const blind={...listener,id:3,bodyPlan:{nodes:[]}};
const source={id:2,alive:true,x:6.5,y:3.5,movedTick:40};
assert.equal(sensoryProfile(blind).vibrationRange,0);
assert.ok(sensoryProfile(listener).vibrationRange>0);
assert.equal(groundVibrationCue(sim,blind,source),null);
const clue=groundVibrationCue(sim,listener,source);
assert.equal(clue?.kind,'vibration');
assert.ok(!('x' in clue)&&!('y' in clue),'no exact hidden organism location');
assert.equal(groundVibrationCue(sim,listener,{...source,movedTick:undefined,intent:'hunt'}),null,'intent is not contact');
assert.equal(groundVibrationCue(sim,listener,{...source,movedTick:0}),null,'old footsteps decay');
assert.ok(groundVibrationCue(sim,listener,{...source,movedTick:undefined,jumpLanding:{tick:40,impact:8}}));
assert.ok(groundVibrationCue(sim,listener,{...source,movedTick:undefined,burrowWork:{schema:1}}));
w.sameLand=()=>false;
assert.equal(groundVibrationCue(sim,listener,source),null,'separate land masses do not conduct');
w.sameLand=()=>true;w.water[w.idx(source.x,source.y)]=1;
assert.equal(groundVibrationCue(sim,listener,source),null,'liquid substrate is not dry footfall');
w.water[w.idx(source.x,source.y)]=0;
assert.equal(groundVibrationCue(sim,listener,{...source,airborne:true}),null);
assert.equal(groundVibrationCue(sim,listener,{...source,diveDepth:.3}),null);
w.moisture[w.idx(listener.x,listener.y)]=1;
assert.equal(groundVibrationCue(sim,listener,source),null,'wet ground weakens marginal pulses');
w.moisture[w.idx(listener.x,listener.y)]=0;
const inside={...listener,underground:true,x:2.5,y:2.5};
const underground={...source,underground:true,x:4.5,y:2.5};
w.subsurface={revision:1,passages:new Map()};
for(let x=2;x<=4;x++)w.subsurface.passages.set(w.idx(x,2),{i:w.idx(x,2),floor:0,entry:x===2});
assert.ok(vibrationPath(sim,inside,underground,8));
assert.ok(groundVibrationCue(sim,inside,underground));
w.subsurface.passages.get(w.idx(3,2)).closed=true;
assert.equal(groundVibrationCue(sim,inside,underground),null);
w.subsurface.passages.get(w.idx(3,2)).closed=false;
w.subsurface.passages.get(w.idx(3,2)).floor=2;
assert.equal(groundVibrationCue(sim,inside,underground),null);
assert.equal(groundVibrationCue(sim,listener,underground),null);
sim.vibrationRules=undefined;
assert.equal(groundVibrationCue(sim,listener,source),null);
const live=new Simulation('GROUND-VIBRATION-RULE',{player:true,bootstrap:false});
const rng=live.rng.state,save=createSimulationSnapshot(live,{savedAt:'fixed'});
assert.equal(restoreSimulationSnapshot(structuredClone(save)).vibrationRules,GROUND_VIBRATIONS.policy);
const historical=structuredClone(save);delete historical.core.vibrationRules;
assert.equal(Object.hasOwn(restoreSimulationSnapshot(historical),'vibrationRules'),false);
const forged=structuredClone(save);forged.core.vibrationRules='ground-vibrations/999';
assert.throws(()=>restoreSimulationSnapshot(forged),/Unknown saved ground vibration/);
assert.equal(live.rng.state,rng,'reads never draw biological RNG');
console.log('Ground contact sensing, physical sources, rock routing, and save policy PASS');
