import assert from 'node:assert/strict';
import {Simulation} from '../src/sim/simulation.js';
import {SPECIES} from '../src/organisms/species.js';
import {makePlan,validatePlan} from '../src/lineage/body-plan.js';
import {founderPlan} from '../src/lineage/body-inheritance.js';
import {partDef} from '../src/lineage/part-registry.js';
import {hasComponent} from '../src/render/part-sprites.js';
import {reproductiveMode,conceptionMode,DUAL_MATERNAL_COST,DUAL_PATERNAL_COST} from '../src/reproduction/reproductive-anatomy.js';
import {conceptionFunding} from '../src/ecology/birth-investment.js';
import {createSimulationSnapshot,restoreSimulationSnapshot} from '../src/persistence/save-manager.js';
const sim=new Simulation('DUAL-ANATOMY-TEST',{player:false,bootstrap:false});
const mother=sim.spawnAnimal('genvo',35,35),father=sim.spawnAnimal('genvo',35,36);
const base=founderPlan();
const placements=base.nodes.map(({partId,parent,socket})=>({partId,parent,socket}));
const plan=(parts)=>makePlan([...placements,...parts.map(([partId,socket])=>({partId,parent:'root',socket}))]);
const egg=plan([['egg-chamber','flank.left']]);
const live=plan([['live-womb','flank.right']]);
const dual=plan([['egg-chamber','flank.left'],['live-womb','flank.right']]);
for(const p of [egg,live,dual])assert.ok(validatePlan(p).ok,'each anatomy is physically mountable');
for(const id of ['egg-chamber','live-womb'])assert.equal(hasComponent(id),true);
assert.equal(reproductiveMode({bodyPlan:base}),'live');
assert.equal(reproductiveMode({bodyPlan:egg}),'egg');
assert.equal(reproductiveMode({bodyPlan:live}),'live');
assert.equal(reproductiveMode({bodyPlan:dual}),'dual');
assert.ok(partDef('egg-chamber').mutationCost+partDef('live-womb').mutationCost>=12,'dual capability occupies substantial mutation budget');
assert.ok(partDef('egg-chamber').upkeep+partDef('live-womb').upkeep>.5);
mother.bodyPlan=dual;mother.sex='F';father.sex='M';
mother.energy=SPECIES.genvo.maxEnergy;mother.hydration=SPECIES.genvo.maxHydration;
father.energy=SPECIES.genvo.maxEnergy;
sim.playerId=mother.id;sim._player=null;
assert.equal(sim.reproduction.cycleBroodStrategy().strategy,'live','gestating player may choose live');
assert.equal(sim.reproduction.cycleBroodStrategy().strategy,'egg','gestating player may choose eggs');
assert.equal(sim.reproduction.cycleBroodStrategy().strategy,'adaptive','gestating player may restore adaptive');
mother.reproductiveStrategy='live';assert.equal(conceptionMode(mother,sim.world),'live');
mother.reproductiveStrategy='egg';assert.equal(conceptionMode(mother,sim.world),'egg');
mother.reproductiveStrategy='adaptive';assert.ok(['egg','live'].includes(conceptionMode(mother,sim.world)));
const rngBefore=sim.rng.state;conceptionMode(mother,sim.world);assert.equal(sim.rng.state,rngBefore,'dual choice does not consume ecology RNG');
const fakeM={energy:110},fakeF={energy:90};
const paid=conceptionFunding(sim.rng,fakeM,fakeF,SPECIES.genvo,'egg',{dual:true});
assert.deepEqual(paid.dualCostPaid,{mother:DUAL_MATERNAL_COST,father:DUAL_PATERNAL_COST});
assert.equal(fakeM.energy,110-DUAL_MATERNAL_COST-paid.birthCost*.35);
assert.equal(fakeF.energy,90-DUAL_PATERNAL_COST-paid.birthCost*.12);
assert.equal(paid.reserveInvestment,paid.birthCost*.47,'switching cost never increases offspring budget');
const onlyEgg={energy:110},onlyFather={energy:90};const standard=conceptionFunding(sim.rng,onlyEgg,onlyFather,SPECIES.genvo,'egg');
assert.equal(standard.dualCostPaid,null,'egg specialists do not pay dual surcharge');
// The mode and both parental body snapshots persist even when preference or anatomy changes later.
mother.reproductiveStrategy='egg';
mother.pregnant={fatherId:father.id,paternalInheritance:structuredClone(father),maternalInheritance:structuredClone(mother),days:0,totalDays:16,
 mode:conceptionMode(mother,sim.world),dualAtConception:true,plannedLitterSize:2,birthCost:34,reserveInvestment:0};
const ground=sim.safeSpawn('genvo');mother.x=ground.x;mother.y=ground.y;father.x=ground.x+.5;father.y=ground.y;
for(const stock of Object.values(sim.world.plants))stock[sim.world.idx(mother.x,mother.y)]=0;
assert.equal(sim.reproduction.cycleBroodStrategy().ok,false,'brood strategy cannot rewrite an existing pregnancy');
const laid=sim.giveBirth(mother);assert.equal(laid.length,2);assert.equal(sim.eggs.length,2);assert.equal(sim.stats.births,0);
assert.ok(laid.every(e=>e.maternalInheritance.bodyPlan.id===dual.id));
mother.bodyPlan=base;mother.reproductiveStrategy='live';
const restored=restoreSimulationSnapshot(structuredClone(createSimulationSnapshot(sim)));
assert.equal(restored.animals.find(a=>a.id===mother.id).reproductiveStrategy,'live');
assert.equal(restored.eggs[0].maternalInheritance.bodyPlan.id,dual.id);
const restoredMother=restored.animals.find(a=>a.id===mother.id);
restoredMother.bodyPlan=dual;restoredMother.reproductiveStrategy='live';
restoredMother.energy=SPECIES.genvo.maxEnergy;restoredMother.hydration=SPECIES.genvo.maxHydration;
restoredMother.pregnant={fatherId:father.id,paternalInheritance:structuredClone(father),maternalInheritance:structuredClone(restoredMother),days:0,totalDays:16,
 mode:conceptionMode(restoredMother,restored.world),dualAtConception:true,plannedLitterSize:1,birthCost:17,reserveInvestment:0};
const eggsBefore=restored.eggs.length,birthsBefore=restored.stats.births;
const liveYoung=restored.giveBirth(restoredMother);
assert.equal(restored.eggs.length,eggsBefore,'live mode creates no more physical eggs');
assert.equal(liveYoung.length,1,'dual-capable body can produce live-born offspring');
assert.equal(restored.stats.births,birthsBefore+1);
// Legacy saves with no selected mode and no specialized parts remain live-bearing.
const old=structuredClone(createSimulationSnapshot(sim));delete old.animals[0].reproductiveStrategy;
const reloaded=restoreSimulationSnapshot(old);
assert.ok(['live','egg','dual'].includes(reproductiveMode(reloaded.animals[0])));
assert.equal(conceptionMode({bodyPlan:base},reloaded.world),'live');
console.log('dual reproductive anatomy: cost, both modes, inherited physical organs, conception freeze, legacy support, save/load PASS');
