import {provideRootFood} from './helpers/finite-root-food.js';
import assert from 'node:assert/strict';
import {Simulation} from '../src/sim/simulation.js';
import {createSimulationSnapshot,restoreSimulationSnapshot} from '../src/persistence/save-manager.js';
import {disturbanceAt,recordSoilDig,SOIL_DISTURBANCE} from '../src/ecology/soil-disturbance.js';
const sim=new Simulation('SOIL-DISTURBANCE',{player:false}),a=sim.animals.find(a=>a.species==='rootling'),ability=sim.partAbilities;
sim.world.water[sim.world.idx(a.x,a.y)]=0;a.energy=30;
provideRootFood(sim,a);const plants=structuredClone(sim.world.plants),rng=sim.rng.state;
assert.equal(ability.disturbedSoilAt(a.x,a.y),0);
assert.ok(ability.dig(a).ok);assert.equal(ability.disturbedSoilAt(a.x,a.y),SOIL_DISTURBANCE.perDig);
const meal=sim.world.idx(a.x,a.y);assert.ok(sim.world.plants.marshroot[meal]<plants.marshroot[meal]);plants.marshroot[meal]=sim.world.plants.marshroot[meal];assert.deepEqual(sim.world.plants,plants,'Only the finite root meal changes plant stocks');assert.equal(sim.rng.state,rng);
const unchanged=structuredClone(ability.soilDisturbance);
assert.equal(ability.dig(a).ok,false);assert.deepEqual(ability.soilDisturbance,unchanged,'Failed or cooldown action leaves no new work');
const restored=restoreSimulationSnapshot(structuredClone(createSimulationSnapshot(sim)));
assert.deepEqual(restored.partAbilities.soilDisturbance,ability.soilDisturbance);
const legacy=structuredClone(createSimulationSnapshot(sim));delete legacy.controllers.partAbilities.soilDisturbance;
const upgraded=restoreSimulationSnapshot(legacy),oldActor=upgraded.animals.find(b=>b.id===a.id);
assert.equal(upgraded.partAbilities.disturbedSoilAt(oldActor.x,oldActor.y),0,'Older saves invent no prior soil work');
oldActor.digUntilTick=0;upgraded.day+=60;
assert.ok(upgraded.partAbilities.dig(oldActor).ok,'Older saves can record new successful digging');
assert.equal(upgraded.partAbilities.disturbedSoilAt(oldActor.x,oldActor.y),SOIL_DISTURBANCE.perDig);
const region=upgraded.regionalEcology.habitat(upgraded.regionalEcology.keyAt(oldActor.x,oldActor.y));
assert.equal(region.habitatModifiers.disturbedSoilCells,1);
assert.equal(region.habitatModifiers.soilDisturbance,SOIL_DISTURBANCE.perDig,'Regional query reads the same canonical tag');
sim.day+=60;assert.equal(ability.disturbedSoilAt(a.x,a.y),0,'No further work means disturbance expires even if actor remains alive');
const records=new Map();for(let i=0;i<20;i++)recordSoilDig(records,1,1,i);
assert.equal(disturbanceAt(records,1,1),1,'Work saturates rather than accumulating unbounded benefit');
assert.equal(disturbanceAt(records,1,31),.5);assert.equal(disturbanceAt(records,1,61),0);
console.log('completed dig only, finite soil disturbance, no plant/RNG creation, time decay and persistence: PASS');
