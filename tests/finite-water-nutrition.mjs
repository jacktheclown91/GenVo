import assert from 'node:assert/strict';
import {Simulation} from '../src/sim/simulation.js';
import {createDraft,place} from '../src/lineage/evolution-draft.js';
import {PARTS} from '../src/lineage/part-registry.js';
const sim=new Simulation('FINITE-WATER-NUTRITION',{player:false}),a=sim.animals.find(a=>a.species==='mosskip');
for(let k=0;k<6;k++)sim.update(null);
const d=createDraft({base:a.bodyPlan,ancestry:Object.keys(PARTS),budget:99});
for(const n of a.bodyPlan.nodes.filter(n=>n.socket?.startsWith('limb.')))assert.ok(place(d,'webbed-leg','root',n.socket).ok);
for(const [part,socket] of [['paddle-tail','tail'],['gill-slits','flank.left'],['filter-mouth','mouth']])assert.ok(place(d,part,'root',socket).ok);
a.bodyPlan=d.plan;a.age=100;a.health=100;a.energy=20;a.x=50.5;a.y=50.5;
sim.world.water[sim.world.idx(a.x,a.y)]=1;
for(const field of Object.values(sim.world.plants))field.fill(0);
for(const field of Object.values(sim.world.freshwaterFood||{}))field.fill(0);
sim.world.carrion.fill(0);sim.animals=[a];sim.rebuildSpatial();
const before=a.energy;sim.phaseMetabolism();
assert.ok(a.energy<before,'empty water must supply no free food energy, even to a fully aquatic filter feeder');
a.intent='drink';a.target={kind:'water',x:a.x,y:a.y};
const beforeDrink=a.energy;sim.resolveInteraction(a);assert.equal(a.energy,beforeDrink,'drinking empty water must not create food');
a.player=true;sim.playerId=a.id;sim._player=a;sim.discovery.collectRelic=()=>null;sim.discovery.poolBonus=()=>16;
const beforeManual=a.energy;const result=sim.playerInteract();assert.equal(a.energy,beforeManual,'manual filtering and still-pool visits require biomass');assert.ok(!result.message.includes('fed'));
console.log('empty water supplies no unbounded aquatic nutrition: PASS');
