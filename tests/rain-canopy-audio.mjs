import assert from 'node:assert/strict';
import {habitatMixTargets} from '../src/audio/habitat.js';
import {HabitatTextures} from '../src/audio/habitat-textures.js';
const target=(kind,canopy,rain,wind=0)=>habitatMixTargets({rain,habitat:{kind,canopy,wind}})['rain-canopy'];
assert.equal(target('woodland',1,0),0,'Dry foliage never fabricates rain');
assert.equal(target('arid',0,1),0,'Rain on bare desert does not invent foliage');
assert.equal(target('woodland',0,1),0,'A label alone does not produce leaves');
assert.ok(target('grassland',.3,.8)>0,'Actual canopy counts independently of the biome label');
assert.ok(target('woodland',1,1)>target('woodland',.3,1));
assert.ok(target('woodland',1,1)>target('woodland',1,.2));
assert.ok(target('woodland',1,1,0)>0,'Rain impacts need no wind');
for(const kind of ['cave','burrow','submerged','silent'])assert.equal(target(kind,1,1),0);
let allocations=0,starts=0;
const param=()=>({value:0,setTargetAtTime(v){this.value=v}});
const node=()=>{allocations++;return{gain:param(),frequency:param(),Q:param(),connect(){},start(){starts++}}};
const ctx={currentTime:0,createGain:node,createBiquadFilter:node,createBufferSource:node,createOscillator:node};
const noise={duration:2.5},textures=new HabitatTextures(ctx,noise,{}),allocated=allocations;
assert.equal(textures.layers.size,5);assert.equal(starts,10);
const leaf=textures.layers.get('rain-canopy');assert.equal(leaf.source.buffer,noise);
for(let i=0;i<1000;i++)textures.update(habitatMixTargets({rain:i%2,habitat:{kind:'woodland',canopy:1,wind:0}}));
assert.equal(allocations,allocated,'Weather updates reuse every source/filter/modulator');
assert.ok(leaf.texture.gain.value-leaf.depth.gain.value>0,'Modulation stays nonnegative');
textures.update(habitatMixTargets({rain:0,habitat:{kind:'woodland',canopy:1}}));
assert.equal(leaf.gain.gain.value,0,'Dry transition targets silence');
console.log('Rain canopy PASS: physical rain/canopy gating, wind independence, enclosure exclusion, bounded shared noise and allocation-free updates.');
