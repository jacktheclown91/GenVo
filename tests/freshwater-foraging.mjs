import assert from 'node:assert/strict';
import {Simulation} from '../src/sim/simulation.js';
import {createDraft,place} from '../src/lineage/evolution-draft.js';
import {PARTS} from '../src/lineage/part-registry.js';
import {bestFreshwaterFood} from '../src/ecology/freshwater-food.js';
import {committedFoodTarget} from '../src/ecology/food-commitment.js';
import {founderPlan} from '../src/lineage/body-inheritance.js';
const sim=new Simulation('FRESHWATER-FORAGE',{player:false});
for(let k=0;k<6;k++)sim.update(null);
const a=sim.animals.find(a=>a.species==='mosskip'),w=sim.world;
const draft=createDraft({base:a.bodyPlan,ancestry:Object.keys(PARTS),budget:99});
for(const n of a.bodyPlan.nodes.filter(n=>n.socket?.startsWith('limb.')))assert.ok(place(draft,'webbed-leg','root',n.socket).ok);
for(const [part,socket] of [['paddle-tail','tail'],['gill-slits','flank.left'],['filter-mouth','mouth']])assert.ok(place(draft,part,'root',socket).ok);
a.bodyPlan=draft.plan;a.x=50.5;a.y=50.5;a.energy=20;a.age=100;
for(const f of Object.values(w.plants))f.fill(0);
for(const f of Object.values(w.freshwaterFood))f.fill(0);
w.carrion.fill(0);w.water[w.idx(a.x,a.y)]=1;w.freshwaterFood.algae[w.idx(a.x,a.y)]=1;
sim.animals=[a];sim.rebuildSpatial();
const target=sim.bestFood(a);assert.equal(target?.kind,'algae','normal food search discovers compatible freshwater');
a.intent='feed';a.target=target;const before=a.energy,stock=w.freshwaterFood.algae[w.idx(a.x,a.y)];sim.resolveInteraction(a);
assert.ok(a.energy>before,'normal feed interaction consumes aquatic food');
assert.ok(w.freshwaterFood.algae[w.idx(a.x,a.y)]<stock);
assert.ok(sim.foraging.options(a).some(o=>o.kind==='algae'),'player food selection uses the same resource');
const result=sim.foraging.consume(a,sim.foraging.options(a).find(o=>o.kind==='algae'));
assert.ok(result.ok);assert.ok(result.message.includes('Algae'));
assert.ok(sim.foraging.state(a).patches.some(p=>p.kind==='algae'),'freshwater meal creates an observable learned patch');
w.freshwaterFood.algae[w.idx(a.x,a.y)]=.8;
const state=sim.cognition.state(a);sim.cognition.observeEnvironment(a,state,{diets:{}});
assert.equal(state.food?.kind,'algae','sensory observation discovers actual compatible water stock');
w.water[w.idx(51,51)]=1;w.freshwaterFood.algae[w.idx(51,51)]=1;
assert.ok(sim.carrying.forageAt(a)>0,'reachable water food contributes to carrying capacity');
// A dry-bodied filter feeder may eat floating food from the bank, but cannot
// acquire underwater prey merely because it knows the pond exists.
w.water.fill(0);for(const field of Object.values(w.freshwaterFood))field.fill(0);
w.water[w.idx(51.5,50.5)]=1;w.freshwaterFood.algae[w.idx(51.5,50.5)]=1;w.buildLandRegions();w.buildHydrology();
const bank={...a,bodyPlan:founderPlan(),adaptations:[],ecoLifestyle:null,x:50.5,y:50.5};
bank.bodyPlan=structuredClone(bank.bodyPlan);bank.bodyPlan.nodes.find(n=>n.socket==='mouth').partId='filter-mouth';
const bankFood=bestFreshwaterFood(sim,bank,3);assert.equal(bankFood?.kind,'algae');assert.equal(w.water[w.idx(bankFood.x,bankFood.y)],0,'bank route remains terrestrial');
bank.intent='feed';bank.target=bankFood;assert.equal(committedFoodTarget(sim,bank),bankFood,'commitment retains source coordinates at the bank');
const bankStock=w.freshwaterFood.algae[w.idx(51.5,50.5)],bankEnergy=bank.energy;sim.resolveInteraction(bank);
assert.ok(bank.energy>bankEnergy);assert.ok(w.freshwaterFood.algae[w.idx(51.5,50.5)]<bankStock);
w.freshwaterFood.algae.fill(0);w.freshwaterFood.larvae[w.idx(51.5,50.5)]=.2;
assert.equal(bestFreshwaterFood(sim,bank,3),null,'submerged prey requires real aquatic access');
console.log('shared freshwater search, interaction and patch learning: PASS');
