import assert from 'node:assert/strict';
import {Simulation} from '../src/sim/simulation.js';
import {createDraft,place} from '../src/lineage/evolution-draft.js';
import {PARTS} from '../src/lineage/part-registry.js';
const sim=new Simulation('MIGRATION-HABITAT',{player:false}),a=sim.animals.find(a=>a.species==='mosskip'),pred=sim.animals.find(a=>a.species==='needlejaw'),w=sim.world;
a.x=50.5;a.y=50.5;pred.x=63.5;pred.y=63.5;sim.animals=[a,pred];sim.rebuildSpatial();
assert.equal(sim.migration.predatorPressure(a,a,6),0,'spatial bucket membership is not actual predator proximity');
pred.x=51.5;pred.y=50.5;sim.rebuildSpatial();assert.ok(sim.migration.predatorPressure(a,a,6)>0);
const draft=createDraft({base:a.bodyPlan,ancestry:Object.keys(PARTS),budget:99});
for(const n of a.bodyPlan.nodes.filter(n=>n.socket?.startsWith('limb.')))assert.ok(place(draft,'webbed-leg','root',n.socket).ok);
for(const [part,socket] of [['paddle-tail','tail'],['gill-slits','flank.left'],['filter-mouth','mouth']])assert.ok(place(draft,part,'root',socket).ok);
a.bodyPlan=draft.plan;sim.animals=[a];sim.rebuildSpatial();
w.water.fill(1);w.temperature.fill(.55);w.buildLandRegions();w.buildHydrology();
for(const f of Object.values(w.freshwaterFood))f.fill(0);
const empty=sim.migration.habitatQuality(a,a.x,a.y);
w.freshwaterFood.algae.fill(1);
const fed=sim.migration.habitatQuality(a,a.x,a.y);
assert.ok(fed.food>empty.food,'compatible real water food contributes to habitat quality');
assert.ok(fed.temp>.9&&fed.water===1,'occupiable water habitat retains temperature and hydration suitability');
assert.ok(fed.score>empty.score);
console.log('migration habitat uses actual predator distances and accessible water food: PASS');
