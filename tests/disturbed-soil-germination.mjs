import assert from 'node:assert/strict';
import {Simulation} from '../src/sim/simulation.js';
import {recordSoilDig} from '../src/ecology/soil-disturbance.js';
const sim=new Simulation('SOIL-GERMINATION',{player:false}),w=sim.world,i=w.idx(48,48),rng=sim.rng.state;
w.water[i]=0;w.seedBank.thistlepod[i]=1;
const ordinary=sim.dispersal.germinate('thistlepod',i,.25,.8,.58),ordinaryDebit=1-w.seedBank.thistlepod[i];
recordSoilDig(sim.partAbilities.soilDisturbance,i,sim.day,1);
w.seedBank.thistlepod[i]=1;
const engineered=sim.dispersal.germinate('thistlepod',i,.25,.8,.58),engineeredDebit=1-w.seedBank.thistlepod[i];
assert.ok(engineeredDebit>ordinaryDebit);assert.ok(engineered>=ordinary);
w.seedBank.thistlepod[i]=0;
assert.equal(sim.dispersal.germinate('thistlepod',i,.25,.8,.58),0,'Disturbance cannot invent propagules');
w.seedBank.thistlepod[i]=1;
assert.equal(sim.dispersal.germinate('thistlepod',i,1,.8,.58),0,'Unsuitable moisture remains unsuitable');
assert.equal(w.seedBank.thistlepod[i],1,'Failed establishment spends no seeds');
sim.day+=60;w.seedBank.thistlepod[i]=1;
assert.equal(sim.dispersal.germinate('thistlepod',i,.25,.8,.58),ordinary,'Engineer absence permits habitat recovery to baseline');
assert.equal(sim.rng.state,rng);
console.log('disturbance-dependent seed-funded germination, no seed creation, habitat gating and decay: PASS');
