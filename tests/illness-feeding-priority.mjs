import assert from 'node:assert/strict';
import {Simulation} from '../src/sim/simulation.js';
import {SPECIES} from '../src/organisms/species.js';
const sim=new Simulation('ILLNESS-FEEDING',{player:true});sim.setPlayerAutonomy(true);
const a=sim.player(),s=SPECIES.genvo;
const relative=sim.spawnAnimal('genvo',49,48.5,[a,sim.animals.find(b=>b.species==='genvo'&&b.id!==a.id)]);
relative.age=s.maturity+10;relative.lineage=true;
sim.animals=[a,relative];a.x=48.5;a.y=48.5;a.age=s.maturity+10;a.reproCooldown=20;
sim.world.water.fill(0);sim.world.moisture.fill(.8);sim.world.buildLandRegions();sim.world.buildHydrology();
for(const field of Object.values(sim.world.plants))field.fill(1);
sim.rebuildSpatial();assert.ok(sim.disease.infect(a,{force:true,source:'fixture'}));
a.energy=s.maxEnergy*.9;a.hydration=s.maxHydration*.9;
assert.equal(sim.familyIllness.decision(a)?.intent,'illness-isolate','Fed infected adult still separates from susceptible family');
a.energy=s.maxEnergy*.2;
sim.phaseDecision(null);
assert.equal(a.intent,'feed','Infected hungry adult must be able to seek an actual meal');
assert.ok(a.target?.kind);assert.ok(a.infected,'Seeking food does not cure infection');
const rng=sim.rng.state;a.energy=s.maxEnergy*.9;a.hydration=s.maxHydration*.4;
assert.equal(sim.familyIllness.decision(a),null,'Thirst must be allowed to reach the drinking decision');
assert.equal(sim.rng.state,rng,'Survival gate consumes no RNG');
a.hydration=s.maxHydration*.9;
assert.equal(sim.familyIllness.decision(a)?.intent,'illness-isolate','Isolation remains available after reserves recover');
console.log('illness positioning yields to feeding/drinking without removing infection or isolation: PASS');
