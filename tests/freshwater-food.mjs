import assert from 'node:assert/strict';
import {Simulation} from '../src/sim/simulation.js';
import {advanceFreshwater,harvestFreshwater,freshwaterPreference} from '../src/ecology/freshwater-food.js';
const sim=new Simulation('FINITE-FOOD-CONSERVATION',{player:false}),w=sim.world;
const other=new Simulation('FINITE-FOOD-CONSERVATION',{player:false});
for(const [kind,field] of Object.entries(w.freshwaterFood))assert.deepEqual(field,other.world.freshwaterFood[kind]);
assert.equal(sim.rng.state,other.rng.state);
const i=w.idx(50.5,50.5);w.water.fill(0);w.water[i]=1;w.fertility.fill(0);w.carrion.fill(0);
for(const field of Object.values(w.freshwaterFood))field.fill(0);
w.freshwaterFood.larvae[i]=.1;w.freshwaterFood.fry[i]=.01;
const larvae=w.freshwaterFood.larvae[i],fry=w.freshwaterFood.fry[i];advanceFreshwater(w);
assert.ok(w.freshwaterFood.larvae[i]<=larvae,'consumers cannot create food without producer biomass');
assert.ok(w.freshwaterFood.fry[i]-fry<=(larvae-w.freshwaterFood.larvae[i])*.2+1e-8,'prey growth consumes its lower trophic source');
for(const field of Object.values(w.freshwaterFood))field.fill(0);
w.freshwaterFood.algae[i]=.1;
const animal={alive:true,x:50.5,y:50.5,bodyPlan:{nodes:[{parent:'root',socket:'mouth',partId:'filter-mouth'}]}};
const first=harvestFreshwater(sim,animal,10);assert.ok(first);assert.ok(first.energyGain<=.8000001);
assert.equal(harvestFreshwater(sim,{...animal},10),null,'competitors cannot reuse consumed stock');
for(const species of ['mosskip','rootling','needlejaw','genvo'])assert.equal(freshwaterPreference({...animal,species},'algae'),1,'mouth rather than origin controls diet');
w.carrion[i]=1;const before=w.fertility[i];advanceFreshwater(w);assert.ok(w.carrion[i]<1);assert.ok(w.fertility[i]>before);
console.log('freshwater stocks, trophic transfer and competing harvests: PASS');
