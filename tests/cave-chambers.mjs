import assert from 'node:assert/strict';
import {Simulation} from '../src/sim/simulation.js';
import {solidTerrainTotal,batchExcavation,excavatePassage,excavationSite,validateSubsurface} from '../src/world/subsurface.js';
import {initializeCaves,validateCaves,CAVES} from '../src/world/natural-caves.js';
import {createSimulationSnapshot,restoreSimulationSnapshot} from '../src/persistence/save-manager.js';
import {undergroundLineOfSight} from '../src/world/cave-optics.js';
import {caveNeighborOpen} from '../src/render/cave-surface.js';
import {undergroundPosition} from '../src/lineage/burrowing.js';

const s=new Simulation('CAVES-GEOLOGY',{naturalCaves:false}),w=s.world;
const mass=solidTerrainTotal(w),rng=s.rng.state,water=w.water.slice();let rebuilds=0;
const build=w.buildHydrology.bind(w);w.buildHydrology=()=>{rebuilds++;return build()};
initializeCaves(w,{generate:true});
assert.equal(rebuilds,1,'initial geological transfers refresh derived hydrology once');
assert.equal(w.subsurface.formation,'fracture-chambers/2');
assert.ok(Math.abs(solidTerrainTotal(w)-mass)<1e-7);assert.equal(s.rng.state,rng);assert.deepEqual(w.water,water);
validateCaves(w,CAVES.policy);
const passages=w.subsurface.passages;
let chamber;
for(const [i,p] of passages)if(!p.entry&&!p.closed&&i%w.n<w.n-1&&[i+1,i+w.n,i+w.n+1].every(j=>passages.has(j)&&!passages.get(j).closed&&Math.abs(passages.get(j).floor-p.floor)<=.6)){chamber=p;break}
assert.ok(chamber,'actual connected 2x2 spaces exist rather than painted widths over one-cell corridors');
const x=chamber.i%w.n+.5,y=(chamber.i/w.n|0)+.5;
assert.equal(caveNeighborOpen(w,chamber,1,0),true);
assert.equal(undergroundLineOfSight(w,x,y,x+1,y+1),true,'shared physical ray crosses the broad cavity');
assert.equal(undergroundPosition(w,{...s.player(),underground:true,x,y},x+1,y+1),true,'the visible chamber is actually traversable');
const repeat=new Simulation('CAVES-GEOLOGY');assert.deepEqual(repeat.world.subsurface,w.subsurface,'geology repeats without biological RNG');
s.caveRules=CAVES.policy;const snap=createSimulationSnapshot(s,{savedAt:'fixed'}),restored=restoreSimulationSnapshot(structuredClone(snap));
assert.deepEqual(restored.world.subsurface,w.subsurface,'exact new formation geometry and ledger persist');
const historical=structuredClone(snap);delete historical.world.subsurface.formation;
const old=restoreSimulationSnapshot(historical);assert.equal(Object.hasOwn(old.world.subsurface,'formation'),false);assert.deepEqual(old.world.subsurface.passages,w.subsurface.passages,'historical geometry is not regenerated by the new initial formation algorithm');
const invalid=structuredClone(snap);invalid.world.subsurface.formation='unknown';assert.throws(()=>restoreSimulationSnapshot(invalid),/formation/);
// Batched transfers publish the same physical state even when work aborts.
const fixture=new Simulation('BATCH-EXCAVATION',{naturalCaves:false}),fw=fixture.world;
let refreshed=0;const rebuild=fw.buildHydrology.bind(fw);fw.buildHydrology=()=>{refreshed++;return rebuild()};
const before=solidTerrainTotal(fw);let i=fw.terrain.elevation.findIndex((v,j)=>!!excavationSite(fw,j));
assert.throws(()=>batchExcavation(fw,()=>{assert.ok(excavatePassage(fw,i));throw Error('injected interruption')}),/interruption/);
assert.equal(refreshed,1,'exception paths publish the derived hydrology for already committed physical transfers');assert.ok(Math.abs(solidTerrainTotal(fw)-before)<1e-7);validateSubsurface(fw,true);
console.log('Geological chambers PASS: actual broad traversable voids, deterministic conserved formation, one derived refresh and exact historical/new save geometry.');
