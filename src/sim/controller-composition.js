// Constructors may read controllers assigned earlier. Keep this explicit order and
// the actual Simulation reference; do not sort, lazily construct or replace owners.
// Restore defers flora generation until saved dispersal state is installed.
export function initializeControllers(sim, {deferDispersalInitialization = false} = {}) {
  sim.lineage = new LineageTracker(sim);
  sim.reproduction = new ReproductionController(sim);
  sim.family = new FamilyController(sim);
  sim.expansion = new FamilyExpansionController(sim);
  sim.familyDirectives = new FamilyDirectiveController(sim);
  sim.cognition = new CognitionController(sim);
  sim.habits = new HabitController(sim);
  sim.evolutionBudget = new EvolutionBudgetController(sim);
  sim.evolutionEditor = new EvolutionEditorController(sim);
  sim.partAbilities = new PartAbilityController(sim);
  sim.discovery = new DiscoveryController(sim);
  sim.territory = new TerritoryController(sim);
  sim.shelter = new ShelterController(sim);
  sim.migration = new MigrationController(sim);
  sim.regionalEcology = new RegionalEcologyController(sim);
  sim.recovery = new RecoveryController(sim);
  sim.carrying = new CarryingPressureController(sim);
  sim.pressure = new SelectionPressureController(sim);
  sim.history = new EnvironmentalHistoryController(sim);
  sim.sustainability = new FamilySustainabilityController(sim);
  sim.populationEcology = new PopulationCenterEcologyController(sim);
  sim.populationMemory = new PopulationPressureMemoryController(sim);
  sim.protoSpeciation = new ProtoSpeciationController(sim);
  sim.evolutionTree = new EvolutionaryTreeController(sim);
  sim.speciesCoexistence = new SpeciesCoexistenceController(sim);
  sim.speciesLifestyle = new SpeciesLifestyleController(sim);
  sim.speciation = new SpeciationController(sim);
  sim.dispersal = new PlantDispersalController(sim, {initialize: !deferDispersalInitialization});
  sim.disease = new DiseaseController(sim);
  sim.social = new SocialController(sim);
  sim.evolution = new EvolutionController(sim);
  sim.specialization = new LineageSpecializationController(sim);
  sim.tendency = new BehavioralTendencyController(sim);
  sim.divergence = new LineageDivergenceController(sim);
  sim.generationProgress = new GenerationProgressionController(sim);
  sim.predator = new PredatorEncounterController(sim);
  sim.exertion = new ExertionController(sim);
  sim.playerCombat = new PlayerCombatController(sim);
  sim.stalkerTerritory = new StalkerTerritoryController(sim);
  sim.foraging = new ForagingController(sim);
  sim.exposure = new WeatherExposureController(sim);
  sim.familyWeather = new FamilyWeatherController(sim);
  sim.illness = new IllnessRecoveryController(sim);
  sim.familyIllness = new FamilyIllnessController(sim);
  sim.injury = new InjuryRecoveryController(sim);
  sim.activity = new ActivityBudgetController(sim);
  sim.wildlifeRhythm = new WildlifeRhythmController(sim);
}
