// E10: inherited mammalian investment. No species whitelist, hidden milk tank,
// free calories, generic replacement for live birth, or independent new fauna.
// All maternal reserves are the existing animal energy and hydration fields.
import {SPECIES} from '../organisms/species.js';
import {hasPart} from '../lineage/part-abilities.js';
import {reproductiveMode} from '../reproduction/reproductive-anatomy.js';

export const MAMMAL=Object.freeze({
 weaningFraction:.42, milkPerLifeStep:.22,
 conversionEnergy:1.46, waterPerMilk:.37,
 parentEnergyReserve:.42, parentWaterReserve:.38,
 contactDistance:1.5, coldTrigger:.40, heatEnergyPerStep:.035,
 heatProtection:.50, coreHeatCostPerLifeStep:.065, hotCoreMultiplier:1.7
});
const distance=(a,b)=>Math.hypot(a.x-b.x,a.y-b.y);
export function mammalianHeat(animal){
 return !!animal?.alive&&hasPart(animal,'endothermic-core')&&hasPart(animal,'fur-mantle');
}
export function canLactate(parent){
 return !!parent?.alive&&hasPart(parent,'mammary-gland')&&mammalianHeat(parent)&&
   reproductiveMode(parent)!=='egg'&&hasPart(parent,'live-womb');
}
export function milkEligible(parent,child){
 if(parent?.underground||child?.underground||parent?.burrowWork||parent?.caveTransit||child?.burrowWork||child?.caveTransit)return false;
 if(!parent?.alive||!child?.alive||!canLactate(parent))return false;
 if(child.hatchedFromEggId!=null||child.lactationParentId!==parent.id)return false;
 const age=child.age/Math.max(1,SPECIES[child.species]?.maturity||1);
 return age<MAMMAL.weaningFraction;
}
// Milk is manufactured on demand. If insufficient reserves exist, the mother
// provides NO free food and the offspring must survive on its own stored energy,
// foraging or other normal parental support.
export function transferMilk(parent,child,{maximum=MAMMAL.milkPerLifeStep}={}){
 if(!milkEligible(parent,child))return{ok:false,reason:'Milk needs a living lactating birth parent and an unweaned live-born child.'};
 if(parent.airborne||child.airborne||parent.perched||child.perched||distance(parent,child)>MAMMAL.contactDistance)
  return{ok:false,reason:'The infant and birth parent must be together on the surface.'};
 const ps=SPECIES[parent.species],cs=SPECIES[child.species];
 const availableEnergy=Math.max(0,parent.energy-ps.maxEnergy*MAMMAL.parentEnergyReserve)/MAMMAL.conversionEnergy;
 const availableWater=Math.max(0,parent.hydration-ps.maxHydration*MAMMAL.parentWaterReserve)/MAMMAL.waterPerMilk;
 const need=Math.max(0,cs.maxEnergy*.83-child.energy);
 const amount=Math.min(Math.max(0,maximum),availableEnergy,availableWater,need);
 if(!(amount>1e-8))return{ok:false,reason:'The child is satisfied, or maternal food or water reserves are too low.'};
 parent.energy-=amount*MAMMAL.conversionEnergy;
 parent.hydration-=amount*MAMMAL.waterPerMilk;
 child.energy=Math.min(cs.maxEnergy,child.energy+amount);
 child.milkMeals=(child.milkMeals||0)+1;
 child.milkTotal=(child.milkTotal||0)+amount;
 return{ok:true,type:'nursing',fed:amount,energyCost:amount*MAMMAL.conversionEnergy,waterCost:amount*MAMMAL.waterPerMilk};
}
// This is heat generated by the adult at a food-energy cost. It only helps a
// nearby newborn in cold actual cells; it does not give the infant warmth by
// virtue of simply carrying a "mammal" label.
export function motherWarmth(parent,child,temperature,{comfort=MAMMAL.coldTrigger}={}){
 if(!milkEligible(parent,child)||!mammalianHeat(parent)||temperature>=Math.max(MAMMAL.coldTrigger,comfort-.04)||distance(parent,child)>MAMMAL.contactDistance||parent.airborne||child.airborne||parent.perched||child.perched)
  return false;
 const s=SPECIES[parent.species];
 if(parent.energy<s.maxEnergy*MAMMAL.parentEnergyReserve+MAMMAL.heatEnergyPerStep)return false;
 parent.energy-=MAMMAL.heatEnergyPerStep;
 return true;
}
export function thermoregulation(animal,temperature){
 if(!mammalianHeat(animal))return{coldFactor:1,extraEnergy:0};
 const spec=SPECIES[animal.species];
 const affordable=animal.energy>spec.maxEnergy*MAMMAL.parentEnergyReserve;
 return{coldFactor:affordable?.66:1,extraEnergy:MAMMAL.coreHeatCostPerLifeStep*(temperature>.75?MAMMAL.hotCoreMultiplier:1)};
}
export function neonatalColdExposure(animal,temperature){
 const stage=(animal?.age||0)/Math.max(1,SPECIES[animal?.species]?.maturity||1);
 if(stage>=.36||temperature>=MAMMAL.coldTrigger)return 1;
 // Babies of *all* anatomies are more susceptible to real cold cells before
 // mature fur and body mass. Mammals can offset it by paid maternal warmth.
 return 1+Math.max(0,MAMMAL.coldTrigger-temperature)*1.6*(1-stage/.36);
}
export function neonatalWarmthFactor(animal,tick,lifeStride){
 return animal?.lastMaternalWarmthTick!=null&&tick-animal.lastMaternalWarmthTick<=lifeStride*2?1-MAMMAL.heatProtection:1;
}
